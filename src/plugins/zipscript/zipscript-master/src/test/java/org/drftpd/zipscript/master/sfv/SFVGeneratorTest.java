package org.drftpd.zipscript.master.sfv;

import org.drftpd.zipscript.common.sfv.SFVInfo;
import org.junit.jupiter.api.Test;

import java.io.BufferedReader;
import java.io.IOException;
import java.io.StringReader;
import java.util.HashMap;
import java.util.Map;

import static org.junit.jupiter.api.Assertions.*;

public class SFVGeneratorTest {

    @Test
    void sortedLowercasePaddedLines() {
        Map<String, Long> entries = new HashMap<>();
        entries.put("b.r01", 0xABCDEF12L);
        entries.put("A.rar", 0x1L);
        entries.put("c.r02", 0xFFFFFFFFL);
        assertEquals("; Generated by DrFTPD SITE RESCAN\r\n"
                + "A.rar 00000001\r\n"
                + "b.r01 abcdef12\r\n"
                + "c.r02 ffffffff\r\n", SFVGenerator.generate(entries));
    }

    @Test
    void emptyEntriesOnlyHeader() {
        assertEquals("; Generated by DrFTPD SITE RESCAN\r\n", SFVGenerator.generate(new HashMap<>()));
    }

    @Test
    void outputIsReadByExistingSfvParser() throws IOException {
        Map<String, Long> entries = new HashMap<>();
        entries.put("x.rar", 0xDEADBEEFL);
        entries.put("y.r00", 0x0000000AL);
        SFVInfo info = SFVInfo.importSFVInfoFromFile(new BufferedReader(new StringReader(SFVGenerator.generate(entries))));
        assertEquals(2, info.getEntries().size());
        assertEquals(0xDEADBEEFL, info.getEntries().get("x.rar"));
        assertEquals(0xAL, info.getEntries().get("y.r00"));
    }

    @Test
    void listableFiles() {
        assertTrue(SFVGenerator.isListable("a.rar"));
        assertTrue(SFVGenerator.isListable("a.nfo"));
        assertFalse(SFVGenerator.isListable("a.sfv"));
        assertFalse(SFVGenerator.isListable("A.SFV"));
        assertFalse(SFVGenerator.isListable("a.rar.bad"));
        assertFalse(SFVGenerator.isListable(".hidden"));
        assertFalse(SFVGenerator.isListable("with space.rar"));
    }
}
