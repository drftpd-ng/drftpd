package org.drftpd.zipscript.master.sfv;

import org.drftpd.master.network.Checksum;

import java.util.Map;
import java.util.TreeMap;

/**
 * Builds the content of an SFV file, in the format read by
 * {@link org.drftpd.zipscript.common.sfv.SFVInfo#importSFVInfoFromFile}.
 */
public final class SFVGenerator {

    public static final String LINE_SEPARATOR = "\r\n";
    public static final String HEADER = "; Generated by DrFTPD SITE RESCAN";

    private SFVGenerator() {
    }

    /**
     * @param entries file name to CRC32
     * @return a comment header followed by one "name crc" line per entry, sorted by name
     * (case insensitive), the CRC as 8 lowercase hex digits
     */
    public static String generate(Map<String, Long> entries) {
        TreeMap<String, Long> sorted = new TreeMap<>(String.CASE_INSENSITIVE_ORDER.thenComparing(String::compareTo));
        sorted.putAll(entries);
        StringBuilder sb = new StringBuilder(HEADER).append(LINE_SEPARATOR);
        for (Map.Entry<String, Long> e : sorted.entrySet()) {
            sb.append(e.getKey()).append(' ').append(Checksum.formatChecksum(e.getValue())).append(LINE_SEPARATOR);
        }
        return sb.toString();
    }

    /**
     * @return true if a file with this name may be listed in a generated SFV: not an SFV or .bad file, not
     * hidden, and no whitespace (the SFV reader splits name and CRC at the first space).
     */
    public static boolean isListable(String name) {
        String lower = name.toLowerCase();
        return !name.startsWith(".")
                && !lower.endsWith(".sfv")
                && !lower.endsWith(RescanOptions.BAD_SUFFIX)
                && name.chars().noneMatch(Character::isWhitespace);
    }
}
