package org.drftpd.master.sitebot;

import org.drftpd.master.network.BlindTrustManager;
import org.drftpd.master.sitebot.config.ServerConfig;
import org.junit.jupiter.api.AfterEach;
import org.junit.jupiter.api.BeforeAll;
import org.junit.jupiter.api.Test;
import org.junit.jupiter.api.Timeout;
import org.junit.jupiter.api.io.TempDir;

import javax.net.ssl.KeyManagerFactory;
import javax.net.ssl.SNIHostName;
import javax.net.ssl.SNIServerName;
import javax.net.ssl.SSLContext;
import javax.net.ssl.SSLException;
import javax.net.ssl.SSLParameters;
import javax.net.ssl.SSLServerSocket;
import javax.net.ssl.SSLSocket;
import javax.net.ssl.TrustManagerFactory;
import javax.net.ssl.X509TrustManager;
import java.io.File;
import java.io.FileInputStream;
import java.io.InputStream;
import java.net.InetAddress;
import java.net.Socket;
import java.nio.charset.StandardCharsets;
import java.nio.file.Path;
import java.security.KeyStore;
import java.security.cert.CertificateException;
import java.security.cert.X509Certificate;
import java.util.ArrayList;
import java.util.List;
import java.util.concurrent.TimeUnit;

import static org.junit.jupiter.api.Assertions.*;

/**
 * TLS verification of the sitebot socket factory ({@link ServerConfig#getSocketFactory()}, the path used by
 * {@link SiteBot#connect()}) against a local TLS server with certificates generated by keytool:
 * with SASL configured the chain must be trusted and the certificate must match the host name.
 */
public class SiteBotTlsVerificationTest {

    private static final String HOST = "localhost";
    private static final char[] STOREPASS = "changeit".toCharArray();

    @TempDir
    static Path _dir;

    /** Self-signed certificate for another host (wrong.example). */
    private static KeyStore _wrongHost;
    /** Self-signed certificate for localhost. */
    private static KeyStore _localhost;

    private SSLServerSocket _serverSocket;
    private Thread _serverThread;

    @BeforeAll
    public static void createCertificates() throws Exception {
        _wrongHost = generate("wrong", "CN=wrong.example", "SAN=dns:wrong.example");
        _localhost = generate("localhost", "CN=localhost", "SAN=dns:localhost");
    }

    @AfterEach
    public void tearDown() throws Exception {
        if (_serverSocket != null) {
            _serverSocket.close();
        }
        if (_serverThread != null) {
            _serverThread.join(5000);
        }
    }

    @Test
    @Timeout(30)
    public void saslRejectsCertificateForAnotherHost() throws Exception {
        // the chain is trusted, only the host name does not match
        startServer(_wrongHost);
        ServerConfig sc = sasl(trusting(_wrongHost), false);
        assertTrue(sc.isTlsVerificationRequired());
        SSLException e = assertThrows(SSLException.class, () -> handshake(sc));
        assertTrue(String.valueOf(e.getMessage()).contains("No subject alternative DNS name matching localhost"),
                String.valueOf(e));
    }

    @Test
    @Timeout(30)
    public void chainOfWrongHostCertificateIsTrusted() throws Exception {
        // control for the tests above: without host name verification the same trust manager accepts it
        startServer(_wrongHost);
        ServerConfig sc = new ServerConfig(HOST, _serverSocket.getLocalPort(), "", true, trusting(_wrongHost));
        assertDoesNotThrow(() -> handshake(sc));
    }

    @Test
    @Timeout(30)
    public void saslRejectsCertificateForAnotherHostWithPlainTrustManager() throws Exception {
        // PartialTrustManager (ssl.strictTrust=true) is a plain X509TrustManager checking the chain only:
        // the host name must still be verified
        startServer(_wrongHost);
        ServerConfig sc = sasl(plain(trusting(_wrongHost)), false);
        SSLException e = assertThrows(SSLException.class, () -> handshake(sc));
        assertTrue(String.valueOf(e.getMessage()).contains("No subject alternative DNS name matching localhost"),
                String.valueOf(e));
    }

    @Test
    @Timeout(30)
    public void saslAcceptsMatchingCertificate() throws Exception {
        startServer(_localhost);
        ServerConfig sc = sasl(trusting(_localhost), false);
        SSLParameters params = handshake(sc);
        assertEquals("HTTPS", params.getEndpointIdentificationAlgorithm());
        assertEquals(List.of(new SNIHostName(HOST)), params.getServerNames());
    }

    @Test
    @Timeout(30)
    public void saslAcceptsMatchingCertificateWithPlainTrustManager() throws Exception {
        startServer(_localhost);
        assertDoesNotThrow(() -> handshake(sasl(plain(trusting(_localhost)), false)));
    }

    @Test
    @Timeout(30)
    public void saslDoesNotUseBlindTrust() throws Exception {
        // ssl.strictTrust=false configures the blind trust manager: with SASL the JDK default trust store
        // is used instead, which does not trust this self-signed certificate even though its name matches
        startServer(_localhost);
        SSLException e = assertThrows(SSLException.class, () -> handshake(sasl(new BlindTrustManager(), false)));
        assertTrue(String.valueOf(e.getMessage()).contains("PKIX path"), String.valueOf(e));
    }

    @Test
    @Timeout(30)
    public void saslAllowInsecureTlsSkipsVerification() throws Exception {
        startServer(_wrongHost);
        ServerConfig sc = sasl(new BlindTrustManager(), true);
        assertFalse(sc.isTlsVerificationRequired());
        SSLParameters params = handshake(sc);
        assertNull(params.getEndpointIdentificationAlgorithm());
    }

    @Test
    @Timeout(30)
    public void withoutSaslBehaviourIsUnchanged() throws Exception {
        // e.g. EFnet without SASL and ssl.strictTrust=false: no verification at all, as before
        startServer(_wrongHost);
        ServerConfig sc = new ServerConfig(HOST, _serverSocket.getLocalPort(), "", true, new BlindTrustManager());
        assertFalse(sc.isTlsVerificationRequired());
        SSLParameters params = handshake(sc);
        assertNull(params.getEndpointIdentificationAlgorithm());
    }

    @Test
    public void hostNameVerificationParameters() throws Exception {
        try (SSLSocket s = (SSLSocket) SSLContext.getDefault().getSocketFactory().createSocket()) {
            SiteBotSSLSocketFactory.enableHostNameVerification(s, "irc.libera.chat");
            assertEquals("HTTPS", s.getSSLParameters().getEndpointIdentificationAlgorithm());
            assertEquals(List.of(new SNIHostName("irc.libera.chat")), s.getSSLParameters().getServerNames());
        }
        for (String ip : new String[]{"127.0.0.1", "::1", "2001:db8::1"}) {
            try (SSLSocket s = (SSLSocket) SSLContext.getDefault().getSocketFactory().createSocket()) {
                SiteBotSSLSocketFactory.enableHostNameVerification(s, ip);
                assertEquals("HTTPS", s.getSSLParameters().getEndpointIdentificationAlgorithm());
                List<SNIServerName> names = s.getSSLParameters().getServerNames();
                assertTrue(names == null || names.isEmpty(), ip + " " + names);
            }
        }
    }

    private ServerConfig sasl(X509TrustManager trustManager, boolean allowInsecureTls) {
        return new ServerConfig(HOST, _serverSocket.getLocalPort(), "", true, trustManager,
                "drftpd", "s3cret", true, false, allowInsecureTls);
    }

    /** Same steps as SiteBot.connect(): create the socket with the server's factory, client mode, handshake. */
    private SSLParameters handshake(ServerConfig sc) throws Exception {
        try (SSLSocket s = (SSLSocket) sc.getSocketFactory().createSocket(sc.getHostName(), sc.getPort())) {
            s.setSoTimeout(10000);
            s.setUseClientMode(true);
            s.startHandshake();
            return s.getSSLParameters();
        }
    }

    private void startServer(KeyStore ks) throws Exception {
        KeyManagerFactory kmf = KeyManagerFactory.getInstance(KeyManagerFactory.getDefaultAlgorithm());
        kmf.init(ks, STOREPASS);
        SSLContext ctx = SSLContext.getInstance("TLS");
        ctx.init(kmf.getKeyManagers(), null, null);
        _serverSocket = (SSLServerSocket) ctx.getServerSocketFactory()
                .createServerSocket(0, 5, InetAddress.getByName(HOST));
        _serverThread = new Thread(() -> {
            while (!_serverSocket.isClosed()) {
                try (Socket s = _serverSocket.accept()) {
                    s.setSoTimeout(10000);
                    ((SSLSocket) s).startHandshake();
                    // wait for the client to close
                    s.getInputStream().read();
                } catch (Exception e) {
                    // handshake refused by the client, or server closed
                }
            }
        }, "fake-tls-ircd");
        _serverThread.setDaemon(true);
        _serverThread.start();
    }

    /** Trust manager trusting exactly the certificate of the given key store (an X509ExtendedTrustManager). */
    private static X509TrustManager trusting(KeyStore ks) throws Exception {
        KeyStore ts = KeyStore.getInstance("PKCS12");
        ts.load(null, null);
        ts.setCertificateEntry("srv", ks.getCertificate("srv"));
        TrustManagerFactory tmf = TrustManagerFactory.getInstance(TrustManagerFactory.getDefaultAlgorithm());
        tmf.init(ts);
        return (X509TrustManager) tmf.getTrustManagers()[0];
    }

    /** A plain X509TrustManager (not extended) like PartialTrustManager, checking the chain only. */
    private static X509TrustManager plain(X509TrustManager delegate) {
        return new X509TrustManager() {
            @Override
            public void checkClientTrusted(X509Certificate[] chain, String authType) throws CertificateException {
                delegate.checkClientTrusted(chain, authType);
            }

            @Override
            public void checkServerTrusted(X509Certificate[] chain, String authType) throws CertificateException {
                delegate.checkServerTrusted(chain, authType);
            }

            @Override
            public X509Certificate[] getAcceptedIssuers() {
                return delegate.getAcceptedIssuers();
            }
        };
    }

    private static KeyStore generate(String name, String dname, String san) throws Exception {
        File file = _dir.resolve(name + ".p12").toFile();
        String keytool = System.getProperty("java.home") + File.separator + "bin" + File.separator + "keytool";
        List<String> cmd = new ArrayList<>(List.of(keytool, "-genkeypair", "-alias", "srv",
                "-keyalg", "EC", "-groupname", "secp256r1", "-sigalg", "SHA256withECDSA",
                "-dname", dname, "-ext", san, "-validity", "2",
                "-storetype", "PKCS12", "-keystore", file.getAbsolutePath(),
                "-storepass", new String(STOREPASS), "-keypass", new String(STOREPASS), "-noprompt"));
        Process p = new ProcessBuilder(cmd).redirectErrorStream(true).start();
        String output = new String(p.getInputStream().readAllBytes(), StandardCharsets.UTF_8);
        assertTrue(p.waitFor(60, TimeUnit.SECONDS), "keytool timed out");
        assertEquals(0, p.exitValue(), "keytool failed: " + output);
        KeyStore ks = KeyStore.getInstance("PKCS12");
        try (InputStream in = new FileInputStream(file)) {
            ks.load(in, STOREPASS);
        }
        return ks;
    }
}
