package org.drftpd.master.master.usermanager;

import org.drftpd.master.tests.DummyEncryptedBeanUserManager;
import org.drftpd.master.usermanager.encryptedjavabeans.EncryptedBeanUser;
import org.drftpd.master.usermanager.encryptedjavabeans.EncryptedBeanUserManager;
import org.junit.jupiter.api.Test;

import java.nio.charset.StandardCharsets;
import java.security.MessageDigest;
import java.util.HexFormat;

import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertFalse;
import static org.junit.jupiter.api.Assertions.assertThrows;
import static org.junit.jupiter.api.Assertions.assertTrue;

/**
 * Hash compatibility fixtures.
 *
 * The stored hashes below were generated by EncryptedBeanUser.setPassword() while DrFTPD still used
 * spring-boot-starter-security 2.7.17 (spring-security-crypto 5.7.11) and bcprov-ext-jdk15on 1.70.
 * They must keep verifying after any upgrade of the password hashing libraries, and newly generated
 * hashes must keep the same format and parameters.
 */
public class EncryptedBeanUserHashCompatTest {

    private static final String PASSWORD = "Fixture-Pass_2026!";
    // p, a-umlaut, ssw, o-umlaut, rd, euro sign: covers the UTF-8 encoding of non-ASCII characters
    private static final String PASSWORD_UTF8 = "p\u00e4ssw\u00f6rd\u20ac";

    private static final String BCRYPT_FIXTURE = "$2a$12$a1ntwWSrW/7avCNyIJz.G.y1juC56MA9hcaWy6oTJAT8ck6xLptCK";
    private static final String BCRYPT_FIXTURE_UTF8 = "$2a$12$FnXyNjUPyFgfvjhxDmCZWeyK43Pj1i1./6h6I/zqpTuB.F1bQDici";
    // bcrypt hash of 80 times 'a': the old library silently truncated passwords to 72 bytes
    private static final String BCRYPT_FIXTURE_LONG = "$2a$12$VzQtEmdPydOp.nzCqpyIEuwbBtDUyZU4hXc4uBX.8/b6ByzpOiS8C";

    private static final String GLFTPD_FIXTURE = "$7d36f09c$3fcf5dd37b908c28cb398199f7e1f27e6f0bd2a7";
    private static final String GLFTPD_FIXTURE_UTF8 = "$87e5b946$c559ea62aab21d204eacb0a851d6c54ee7f45f25";

    private static final String ARGON2_FIXTURE = "$argon2id$v=19$m=4096,t=3,p=1$a089fzY2C09GcH7YcJK71A$AfCJ71P0b1TWtepHZi+7AZvnqsIEdOSgSL57waRXU80";
    private static final String ARGON2_FIXTURE_UTF8 = "$argon2id$v=19$m=4096,t=3,p=1$0CNu/x9boemVoxdNe7Qt3g$42HhPPa/r3VrQJsmOxCvaEkl2X32kp5qN7Go3LzT50I";

    private static class StoredHashUser extends EncryptedBeanUser {
        private final String _storedHash;

        StoredHashUser(EncryptedBeanUserManager manager, int encryption, String storedHash) {
            super(manager, "compat");
            setEncryption(encryption);
            _storedHash = storedHash;
        }

        @Override
        public String getPassword() {
            return _storedHash;
        }
    }

    private static void assertStoredHash(int encryption, String storedHash, String password) {
        DummyEncryptedBeanUserManager manager = new DummyEncryptedBeanUserManager(encryption);
        assertTrue(new StoredHashUser(manager, encryption, storedHash).checkPassword(password),
                "correct password rejected for " + storedHash);
        assertFalse(new StoredHashUser(manager, encryption, storedHash).checkPassword(password + "x"),
                "wrong password accepted for " + storedHash);
        assertFalse(new StoredHashUser(manager, encryption, storedHash).checkPassword(password.toUpperCase()),
                "wrong password accepted for " + storedHash);
    }

    private static String assertFreshHash(int encryption, String password, String formatRegex) {
        DummyEncryptedBeanUserManager manager = new DummyEncryptedBeanUserManager(encryption);
        EncryptedBeanUser user = new EncryptedBeanUser(manager, "fresh");
        user.setPassword(password);
        String hash = user.getPassword();
        assertTrue(hash.matches(formatRegex), "unexpected hash format: " + hash);
        assertEquals(encryption, user.getEncryption());
        assertTrue(user.checkPassword(password));
        assertFalse(user.checkPassword(password + "x"));
        assertStoredHash(encryption, hash, password);
        return hash;
    }

    @Test
    public void testBcryptFixtures() {
        assertStoredHash(EncryptedBeanUserManager.PASSCRYPT_BCRYPT, BCRYPT_FIXTURE, PASSWORD);
        assertStoredHash(EncryptedBeanUserManager.PASSCRYPT_BCRYPT, BCRYPT_FIXTURE_UTF8, PASSWORD_UTF8);
    }

    @Test
    public void testBcryptFreshHash() {
        // $2a$, cost 12
        String bcrypt = "^[$]2a[$]12[$][./A-Za-z0-9]{53}$";
        assertFreshHash(EncryptedBeanUserManager.PASSCRYPT_BCRYPT, PASSWORD, bcrypt);
        assertFreshHash(EncryptedBeanUserManager.PASSCRYPT_BCRYPT, PASSWORD_UTF8, bcrypt);
    }

    @Test
    public void testBcryptPasswordLongerThan72Bytes() throws Exception {
        int bcrypt = EncryptedBeanUserManager.PASSCRYPT_BCRYPT;
        DummyEncryptedBeanUserManager manager = new DummyEncryptedBeanUserManager(bcrypt);

        // Existing hashes of long passwords still verify (bcrypt only uses the first 72 bytes)
        assertTrue(new StoredHashUser(manager, bcrypt, BCRYPT_FIXTURE_LONG).checkPassword("a".repeat(80)));
        assertTrue(new StoredHashUser(manager, bcrypt, BCRYPT_FIXTURE_LONG).checkPassword("a".repeat(72)));
        assertFalse(new StoredHashUser(manager, bcrypt, BCRYPT_FIXTURE_LONG).checkPassword("a".repeat(71)));
        assertFalse(new StoredHashUser(manager, bcrypt, BCRYPT_FIXTURE_LONG).checkPassword("b".repeat(80)));

        // Spring Security 6 refuses to create a bcrypt hash of more than 72 bytes instead of truncating
        EncryptedBeanUser user = new EncryptedBeanUser(manager, "long");
        assertThrows(IllegalArgumentException.class, () -> user.setPassword("a".repeat(80)));

        // A login that would convert a legacy hash to bcrypt must still succeed and keep the legacy hash
        String longPassword = "c".repeat(80);
        String md5 = HexFormat.of().formatHex(MessageDigest.getInstance("MD5")
                .digest(longPassword.getBytes(StandardCharsets.ISO_8859_1)));
        StoredHashUser legacy = new StoredHashUser(manager, EncryptedBeanUserManager.PASSCRYPT_MD5, md5);
        assertTrue(legacy.checkPassword(longPassword));
        assertEquals(EncryptedBeanUserManager.PASSCRYPT_MD5, legacy.getEncryption());
    }

    @Test
    public void testGlftpdFixtures() {
        assertStoredHash(EncryptedBeanUserManager.PASSCRYPT_GLFTPD, GLFTPD_FIXTURE, PASSWORD);
        assertStoredHash(EncryptedBeanUserManager.PASSCRYPT_GLFTPD, GLFTPD_FIXTURE_UTF8, PASSWORD_UTF8);
    }

    @Test
    public void testGlftpdFreshHash() {
        // "$" + 4 byte salt in hex + "$" + 20 byte PBKDF2-HMAC-SHA1 hash in hex
        String glftpd = "^[$][0-9a-f]{8}[$][0-9a-f]{40}$";
        assertFreshHash(EncryptedBeanUserManager.PASSCRYPT_GLFTPD, PASSWORD, glftpd);
        assertFreshHash(EncryptedBeanUserManager.PASSCRYPT_GLFTPD, PASSWORD_UTF8, glftpd);
    }

    @Test
    public void testArgon2Fixtures() {
        assertStoredHash(EncryptedBeanUserManager.PASSCRYPT_ARGON2, ARGON2_FIXTURE, PASSWORD);
        assertStoredHash(EncryptedBeanUserManager.PASSCRYPT_ARGON2, ARGON2_FIXTURE_UTF8, PASSWORD_UTF8);
    }

    @Test
    public void testArgon2FreshHash() {
        // argon2id, m=4096 KiB, t=3, p=1, 16 byte salt (22 base64 chars), 32 byte hash (43 base64 chars)
        String argon2 = "^[$]argon2id[$]v=19[$]m=4096,t=3,p=1[$][A-Za-z0-9+/]{22}[$][A-Za-z0-9+/]{43}$";
        assertFreshHash(EncryptedBeanUserManager.PASSCRYPT_ARGON2, PASSWORD, argon2);
        assertFreshHash(EncryptedBeanUserManager.PASSCRYPT_ARGON2, PASSWORD_UTF8, argon2);
    }
}
